using System.Collections.Generic;
using System.Linq;
using Verse;
using CombatExtended;

namespace CEReloaded
{
    // The only correct way to delete a loadout. CE's own LoadoutManager.RemoveLoadout knows exactly ONE
    // reference to the deleted object - pawns whose AssignedLoadouts VALUE is that object - and resets
    // those to the default. Everything else in this mod points to it via a NUMBER, and none of these
    // numbers was ever cleaned up:
    //
    //   1. A colonist's personal anchor hangs off the template via CE's own parentID. A personalized
    //      colonist is NOT assigned to the template directly, but to their anchor - so RemoveLoadout
    //      doesn't see them at all. Until the next load this goes unnoticed, because CE's
    //      Loadout._parent still caches the deleted reference; after the next load the cache is empty,
    //      GetLoadoutById finds nothing, ParentLoadout returns null (and does NOT reset _parentID - that
    //      only happens in the "found" branch), and DisplayLoadout stops at the anchor.
    //      The colonist then shows its internal anchor name as the loadout.
    //   2. CE's GetUniqueLoadoutID is Max(uniqueID)+1, so IDs are REUSED after deletion - and anchors
    //      almost always carry the highest. Every leftover number therefore sooner or later points to an
    //      unrelated new object: a freshly created template inherits the packs of a dead colonist, a new
    //      pack counts as "generated by us", a plan finds the wrong pack again.
    //
    // That is why EVERY place where a loadout ID survives is cleaned here - the three side records named
    // above plus packPlanIds, which has the same trap (value = pack ID; the self-healing in
    // FindGeneratedPackForPlan only kicks in when the ID points into nothing, and with a recycled ID it
    // no longer does).
    public static class LoadoutDeletionUtility
    {
        public static void Delete(Loadout lo)
        {
            if (lo == null) return;
            DeleteInternal(lo, new HashSet<int>());
        }

        // Convenience for the bulk delete buttons, and at the same time the place where the list is
        // materialized: several call sites used to iterate directly over LoadoutManager.Loadouts
        // while deletion modifies exactly that list.
        public static int DeleteAll(IEnumerable<Loadout> loadouts)
        {
            List<Loadout> doomed = (loadouts ?? Enumerable.Empty<Loadout>()).Where(l => l != null).ToList();
            var visited = new HashSet<int>();
            foreach (Loadout lo in doomed) DeleteInternal(lo, visited);
            return doomed.Count;
        }

        // Birth hygiene for a RECYCLED ID (Patch_LoadoutManager_AddLoadout): a freshly created loadout
        // must not inherit anything left behind by an IDENTICALLY NUMBERED predecessor that vanished past
        // our deletion paths (CE editor, other mods). Two things: the side records forget the ID, and
        // leftover child parentIDs are detached -
        // NOT deleted as in the deletion path: an anchor with a dangling parentID may still belong to a
        // living colonist, and deleting it would throw that colonist back to the default.
        internal static void ScrubRecycledId(Loadout newborn)
        {
            if (newborn == null) return;
            int id = newborn.UniqueID;
            ForgetSideBooks(id);
            List<Loadout> all = LoadoutManager.Loadouts;
            if (all == null) return;
            Loadout none = all.FirstOrDefault(l => l != null && l.defaultLoadout);
            foreach (Loadout child in all.Where(l => l != null && l != newborn && l.parentID == id).ToList())
                child.parentID = AmmoAssignmentUtility.IsAmmoLink(child) && none != null ? none.UniqueID : 0;
        }

        // visited guards against the recursion (anchors without content of their own are deleted along
        // with it) running in a circle. Our own paths cannot create an anchor-to-anchor chain, but CE's
        // parentID is a freely settable field, and this function deletes things.
        private static void DeleteInternal(Loadout lo, HashSet<int> visited)
        {
            if (lo == null || !visited.Add(lo.UniqueID)) return;
            int id = lo.UniqueID;

            RepointChildren(lo, id, visited);
            ForgetSideBooks(id);
            LoadoutManager.RemoveLoadout(lo);
        }

        // Everything that had this loadout as its CE parent gets a new target - because after ID
        // recycling a leftover parentID is worse than a broken one: it then points to some new object
        // instead of nothing.
        private static void RepointChildren(Loadout lo, int id, HashSet<int> visited)
        {
            List<Loadout> all = LoadoutManager.Loadouts;
            if (all == null) return;
            Loadout none = all.FirstOrDefault(l => l != null && l.defaultLoadout);
            foreach (Loadout child in all.Where(l => l != null && l != lo && l.parentID == id).ToList())
            {
                if (!AmmoAssignmentUtility.IsAmmoLink(child))
                {
                    // A normal loadout with a parent (CE's own editor can do that): it loses the inherited
                    // slots but keeps its name and own content - "no parent" is a perfectly valid state
                    // for it.
                    child.parentID = 0;
                    continue;
                }
                // An anchor WITHOUT content of its own is pure bookkeeping: delete it too, then CE's
                // RemoveLoadout cleanly resets its colonist to the default - exactly what a colonist
                // assigned directly to the template gets as well.
                if (!HasOwnContent(child)) { DeleteInternal(child, visited); continue; }
                // An anchor WITH content (personal ammo, packs, sidearm) is re-parented instead of
                // deleted. Deleting it would be silent data loss from an action whose name only says
                // "delete this template"; re-parented to the default, the colonist keeps their extras,
                // reads as "no template" (not as an internal anchor name), and the next assignment
                // re-attaches the same anchor with its extras to the new template - that is the
                // documented promise of EnsureAmmoLink.
                child.parentID = none != null ? none.UniqueID : 0;
            }
        }

        // Does this anchor carry anything that would be lost on deletion? The "deliberately empty" flag
        // counts too: it IS a player decision, even though it shows as an absence of slots.
        // OwnSlots null-safe: CE's _slots goes unguarded through Scribe_Collections and comes back as null
        // from a save without slots - CE itself handles it with ?., and both places in
        // Patch_Loadout_MultiParentSlots check it as well. A deletion depends on it here.
        private static bool HasOwnContent(Loadout anchor) =>
            (anchor.OwnSlots != null && anchor.OwnSlots.Count > 0)
            || MultiParentUtility.GetExtraParentIds(anchor).Count > 0
            || AmmoAssignmentUtility.IsAmmoCleared(anchor);

        private static void ForgetSideBooks(int id)
        {
            MultiParentUtility.ForgetLoadout(id);
            // The link role -> its loadout. It is the reason a role no longer has to be recognized by
            // its name - and therefore the fifth number that needs cleaning here.
            // If it stayed, the next template with the recycled ID would pose as a role.
            RoleUtility.ForgetRoleLoadout(id);
            CEReloadedGameComponent comp = CEReloadedGameComponent.Cached;
            if (comp == null) return;
            comp.ammoExplicitlyCleared.Remove(id);
            // The exclusion list for roles/loadouts - sixth number, same trap: after recycling a
            // leftover ID would block a completely unrelated new template, and nobody would ever find
            // out why the automation avoids it.
            comp.disabledLoadouts.Remove(id);
            comp.managedLoadoutIds.Remove(id);
            comp.packLoadoutIds.Remove(id);
            foreach (string plan in comp.packPlanIds.Where(kv => kv.Value == id).Select(kv => kv.Key).ToList())
                comp.packPlanIds.Remove(plan);
        }
    }
}
